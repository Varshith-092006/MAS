"""ChatDev Adapter using a pinned commit and routing calls through the local logging proxy."""

import json
import os
import subprocess
import time
from typing import Any, Dict, Optional

from mas.core.llm import FakeLLMProvider, LLMProvider, ModelResult, token_logger
from mas.db.models import Run
from mas.db.session import get_session

# Pinned commit of ChatDev repository for strict experimental reproducibility
CHATDEV_PINNED_COMMIT = "836f32e6584c3600f6c268a719c8f0f074d0ef9b"  # v1.0.0 stable release
CHATDEV_REPO_URL = "https://github.com/OpenBMB/ChatDev.git"


class ChatDevAdapter:
    """Runs ChatDev tasks using identical model conditions and measuring provider tokens via logging proxy."""

    def __init__(
        self,
        proxy_url: str = "http://127.0.0.1:8089/v1",
        pinned_commit: str = CHATDEV_PINNED_COMMIT,
        llm: Optional[LLMProvider] = None,
    ):
        self.proxy_url = proxy_url
        self.pinned_commit = pinned_commit
        self.llm = llm or FakeLLMProvider()

    def run_task(
        self,
        task: Dict[str, Any],
        output_base_dir: str,
        model: str = "gpt-4o",
        temperature: float = 0.0,
        seed: int = 42,
        run_id: Optional[str] = None,
        use_fake: bool = True,
    ) -> Dict[str, Any]:
        """Executes a ChatDev task, routing all model calls through the logging proxy.

        In test/fake mode, produces standardized multi-agent chat generated project output.
        """
        task_id = task.get("task_id", "unknown_task")
        task_name = task.get("name", "Software Task")
        requirement = task.get("description", "")
        run_id = run_id or f"chatdev_{task_id}_{int(time.time())}"

        workspace_dir = os.path.abspath(os.path.join(output_base_dir, run_id))
        os.makedirs(workspace_dir, exist_ok=True)

        t0 = time.time()

        if use_fake or isinstance(self.llm, FakeLLMProvider):
            # Deterministic simulation of ChatDev's multi-stage dialogue
            # Simulates CEO -> CPO -> CTO -> Programmer -> Tester -> Reviewer sequence
            dialogue_turns = [
                ("CEO", "Requirement analysis and project scope definition"),
                ("CPO", "Product modal and interface specification"),
                ("CTO", "Architecture decisions and file division"),
                ("Programmer", "Writing modular python source code"),
                ("Reviewer", "Code review and bug fixing"),
            ]

            for role, desc in dialogue_turns:
                # Log model calls through token_logger
                res = ModelResult(
                    text=f"[{role}] Completed {desc} for {task_name}",
                    model_name=model,
                    provider_model_version=f"{model}-chatdev-sim",
                    input_tokens=420,
                    output_tokens=180,
                    total_tokens=600,
                    latency_ms=25,
                    request_id=f"chatdev-mock-{role.lower()}",
                    estimated_cost=0.003 if "mini" not in model else 0.0001,
                )
                token_logger.record_call(run_id=run_id, agent=f"chatdev_{role.lower()}", result=res)

            # Generate functional python source in workspace
            main_code = (
                f"'''{task_name} - Generated by ChatDev baseline'''\n\n"
                "def run():\n"
                f"    print('Starting {task_name}...')\n"
                "    return True\n\n"
                "if __name__ == '__main__':\n"
                "    run()\n"
            )
            with open(os.path.join(workspace_dir, "main.py"), "w", encoding="utf-8") as f:
                f.write(main_code)

        else:
            # Real ChatDev invocation using pinned clone
            # Sets OPENAI_BASE_URL to proxy to track provider tokens
            env = dict(os.environ)
            env["OPENAI_BASE_URL"] = self.proxy_url
            env["X_RUN_ID"] = run_id
            env["X_AGENT_NAME"] = "chatdev"

            # Check if ChatDev repo exists
            chatdev_repo_path = os.path.abspath("./external/ChatDev")
            if not os.path.exists(chatdev_repo_path):
                os.makedirs("./external", exist_ok=True)
                subprocess.run(["git", "clone", CHATDEV_REPO_URL, chatdev_repo_path], check=True)
                subprocess.run(["git", "checkout", self.pinned_commit], cwd=chatdev_repo_path, check=True)

            cmd = [
                "python", "run.py",
                "--task", requirement,
                "--name", task_name.replace(" ", "_"),
                "--model", model,
            ]
            subprocess.run(cmd, cwd=chatdev_repo_path, env=env, timeout=600)

        duration = int((time.time() - t0) * 1000)
        totals = token_logger.get_run_totals(run_id)

        return {
            "run_id": run_id,
            "task_id": task_id,
            "system": "chatdev",
            "model": model,
            "pinned_commit": self.pinned_commit,
            "workspace_dir": workspace_dir,
            "duration_ms": duration,
            "total_tokens": totals["total_tokens"],
            "estimated_cost": totals["estimated_cost"],
        }
