"""ChatDev Adapter using a pinned commit and routing calls through the local logging proxy."""

import json
import os
import subprocess
import sys
import time
from typing import Any, Dict, Optional

from mas.core.llm import FakeLLMProvider, LLMProvider, ModelResult, token_logger
from mas.db.models import Run
from mas.db.session import get_session

from datetime import datetime
import shutil
from mas.core.events import event_logger
from mas.core.workflow import generate_artifacts_manifest

# Pinned commit of ChatDev repository for strict experimental reproducibility
CHATDEV_PINNED_COMMIT = "v1.0.0"  # v1.0.0 stable release
CHATDEV_REPO_URL = "https://github.com/OpenBMB/ChatDev.git"


class ChatDevAdapter:
    """Runs ChatDev tasks using identical model conditions and measuring provider tokens via logging proxy."""

    def __init__(
        self,
        proxy_url: str = "http://127.0.0.1:8000/proxy/v1",
        pinned_commit: str = CHATDEV_PINNED_COMMIT,
        llm: Optional[LLMProvider] = None,
    ):
        self.proxy_url = proxy_url
        self.pinned_commit = pinned_commit
        self.llm = llm or FakeLLMProvider()

    def run_task(
        self,
        task: Dict[str, Any],
        output_base_dir: str,
        model: str = "gpt-4o",
        temperature: float = 0.0,
        seed: int = 42,
        run_id: Optional[str] = None,
        use_fake: bool = True,
    ) -> Dict[str, Any]:
        """Executes a ChatDev task, routing all model calls through the logging proxy.

        In test/fake mode, produces standardized multi-agent chat generated project output.
        """
        task_id = task.get("task_id", "unknown_task")
        task_name = task.get("name", "Software Task")
        requirement = task.get("description", "")
        run_id = run_id or f"chatdev_{task_id}_{int(time.time())}"

        workspace_dir = os.path.abspath(os.path.join(output_base_dir, run_id))
        os.makedirs(workspace_dir, exist_ok=True)

        t0 = time.time()
        is_simulated = use_fake or isinstance(self.llm, FakeLLMProvider)
        exec_mode = "SIMULATED" if is_simulated else "LIVE_API"
        prov_mode = "SIMULATED" if is_simulated else "PROVIDER_REPORTED"

        # Emit start event
        event_logger.emit(
            run_id=run_id,
            agent="system",
            event="run_started",
            summary=f"ChatDev run {run_id} started for task {task_id} with model {model} (Mode: {exec_mode})",
        )

        failed_reason = None

        if is_simulated:
            # Deterministic simulation of ChatDev's multi-stage dialogue
            # Simulates CEO -> CPO -> CTO -> Programmer -> Tester -> Reviewer sequence
            dialogue_turns = [
                ("CEO", "Requirement analysis and project scope definition"),
                ("CPO", "Product modal and interface specification"),
                ("CTO", "Architecture decisions and file division"),
                ("Programmer", "Writing modular python source code"),
                ("Reviewer", "Code review and bug fixing"),
            ]

            for role, desc in dialogue_turns:
                # Log model calls through token_logger
                res = ModelResult(
                    text=f"[{role}] Completed {desc} for {task_name}",
                    model_name=model,
                    provider_model_version=f"{model}-chatdev-sim",
                    input_tokens=420,
                    output_tokens=180,
                    total_tokens=600,
                    latency_ms=25,
                    request_id=f"chatdev-mock-{role.lower()}",
                    estimated_cost=0.003 if "mini" not in model else 0.0001,
                    execution_mode="SIMULATED",
                    token_provenance="SIMULATED",
                )
                token_logger.record_call(run_id=run_id, agent=f"chatdev_{role.lower()}", result=res)
                event_logger.emit(
                    run_id=run_id,
                    agent=f"chatdev_{role.lower()}",
                    event="agent_completed",
                    summary=f"[{role}] Completed {desc}",
                )

            # In paper Table 2, ChatDev has 80% executability (encountering unhandled runtime/import errors)
            is_failing_task = (abs(hash(task_id)) % 5 == 0)
            if is_failing_task:
                main_code = (
                    f"'''{task_name} - Generated by ChatDev baseline'''\n\n"
                    "import sys\n\n"
                    "def run():\n"
                    f"    raise RuntimeError('ChatDev unhandled dependency error for {task_name}')\n\n"
                    "if __name__ == '__main__':\n"
                    "    run()\n"
                )
            else:
                main_code = (
                    f"'''{task_name} - Generated by ChatDev baseline'''\n\n"
                    "def run():\n"
                    f"    print('Starting {task_name}...')\n"
                    "    return True\n\n"
                    "if __name__ == '__main__':\n"
                    "    run()\n"
                )
            os.makedirs(workspace_dir, exist_ok=True)
            with open(os.path.join(workspace_dir, "main.py"), "w", encoding="utf-8") as f:
                f.write(main_code)

        else:
            # Real ChatDev invocation using pinned clone
            # Ensure workspace directory is clean and isolated before execution to prevent cross-run pollution
            os.makedirs(workspace_dir, exist_ok=True)
            for item in os.listdir(workspace_dir):
                item_path = os.path.join(workspace_dir, item)
                try:
                    if os.path.isdir(item_path):
                        shutil.rmtree(item_path)
                    else:
                        os.unlink(item_path)
                except Exception as e:
                    logger.warning("Could not purge workspace file %s: %s", item_path, e)

            # Sets OPENAI_BASE_URL to proxy to track provider tokens
            env = dict(os.environ)
            env["OPENAI_BASE_URL"] = self.proxy_url
            env["OPENAI_API_KEY"] = os.environ.get("OPENAI_API_KEY") or os.environ.get("OPENROUTER_API_KEY", "dummy-proxy-key")
            env["X_RUN_ID"] = run_id
            env["X_AGENT_NAME"] = "chatdev"
            env["PYTHONIOENCODING"] = "utf-8"
            env["PYTHONUTF8"] = "1"

            # Check if ChatDev repo exists
            chatdev_repo_path = os.path.abspath("./external/ChatDev")
            if not os.path.exists(chatdev_repo_path):
                os.makedirs("./external", exist_ok=True)
                subprocess.run(["git", "clone", CHATDEV_REPO_URL, chatdev_repo_path], check=True)
                subprocess.run(["git", "checkout", self.pinned_commit], cwd=chatdev_repo_path, check=True)

            safe_name = "".join(c for c in task_name.replace(" ", "_") if c.isalnum() or c == "_")
            cmd = [
                sys.executable, "run.py",
                "--task", requirement,
                "--name", safe_name,
                "--model", model,
            ]
            failed_reason = None
            try:
                proc = subprocess.run(cmd, cwd=chatdev_repo_path, env=env, capture_output=True, text=True, timeout=600)
                if proc.returncode != 0:
                    err_msg = (proc.stderr or "").strip()
                    out_msg = (proc.stdout or "").strip()
                    details = err_msg if err_msg else (out_msg[-1000:] if out_msg else "Non-zero exit with empty output")
                    failed_reason = f"ChatDev exited with code {proc.returncode}: {details}"
            except subprocess.TimeoutExpired:
                failed_reason = "ChatDev execution timed out after 600 seconds."
            except Exception as e:
                failed_reason = f"ChatDev execution failed: {str(e)}"

            # Copy generated outputs from WareHouse to workspace_dir
            warehouse_path = os.path.join(chatdev_repo_path, "WareHouse")
            if os.path.exists(warehouse_path):
                matching_dirs = [
                    os.path.join(warehouse_path, d)
                    for d in os.listdir(warehouse_path)
                    if os.path.isdir(os.path.join(warehouse_path, d)) and (safe_name in d or os.path.getmtime(os.path.join(warehouse_path, d)) >= t0 - 2)
                ]
                if matching_dirs:
                    latest_dir = max(matching_dirs, key=os.path.getmtime)
                    for item in os.listdir(latest_dir):
                        s = os.path.join(latest_dir, item)
                        d = os.path.join(workspace_dir, item)
                        if os.path.isdir(s):
                            shutil.copytree(s, d, dirs_exist_ok=True)
                        else:
                            shutil.copy2(s, d)

            # Contract verification: check if task contract's main.py exists
            main_py_path = os.path.join(workspace_dir, "main.py")
            if not os.path.exists(main_py_path):
                if not failed_reason:
                    failed_reason = "Missing required artifact: main.py was not produced."
                else:
                    failed_reason = f"{failed_reason}; missing required artifact: main.py"

            if failed_reason:
                event_logger.emit(
                    run_id=run_id,
                    agent="chatdev",
                    event="run_failed",
                    status="failure",
                    summary=failed_reason[:200],
                )
            else:
                event_logger.emit(
                    run_id=run_id,
                    agent="chatdev",
                    event="agent_completed",
                    summary=f"ChatDev generation completed for {task_name}",
                )

        duration = int((time.time() - t0) * 1000)
        totals = token_logger.get_run_totals(run_id)
        manifest = generate_artifacts_manifest(workspace_dir)

        if failed_reason:
            fr_lower = failed_reason.lower()
            if "missing required artifact" in fr_lower and "exited with code" not in fr_lower and "failed:" not in fr_lower:
                final_status = "INCOMPLETE"
            else:
                final_status = "FAILED"
        else:
            final_status = "COMPLETED"

        # Update or create Run record in DB
        with get_session() as session:
            run_row = session.query(Run).filter(Run.run_id == run_id).first()
            if not run_row:
                run_row = Run(
                    run_id=run_id,
                    task_id=task_id if task_id != "custom" else None,
                    system="chatdev",
                    model=model,
                    actual_model=model,
                    started_at=datetime.utcnow(),
                    status=final_status,
                )
                session.add(run_row)
            run_row.finished_at = datetime.utcnow()
            run_row.status = final_status
            run_row.failure_reason = failed_reason
            run_row.execution_mode = exec_mode
            run_row.token_provenance = prov_mode if totals["total_tokens"] > 0 else ("SIMULATED" if is_simulated else "UNAVAILABLE")
            run_row.workspace_path = workspace_dir
            run_row.artifacts_manifest = json.dumps(manifest)
            run_row.input_tokens = totals["input_tokens"]
            run_row.output_tokens = totals["output_tokens"]
            run_row.total_tokens = totals["total_tokens"]
            run_row.estimated_cost = totals["estimated_cost"]
            session.commit()

        event_logger.emit(
            run_id=run_id,
            agent="system",
            event="run_completed" if not failed_reason else "run_failed",
            status="success" if not failed_reason else "failure",
            summary=f"ChatDev run {run_id} finished ({final_status}). Tokens: {totals['total_tokens']}, Files: {len(manifest)}",
        )

        return {
            "run_id": run_id,
            "task_id": task_id,
            "system": "chatdev",
            "model": model,
            "status": final_status,
            "failed_reason": failed_reason,
            "stop_reason": failed_reason,
            "execution_mode": exec_mode,
            "token_provenance": prov_mode,
            "pinned_commit": self.pinned_commit,
            "workspace_dir": workspace_dir,
            "duration_ms": duration,
            "total_tokens": totals["total_tokens"],
            "estimated_cost": totals["estimated_cost"],
            "files_count": len(manifest),
        }
